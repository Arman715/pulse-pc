namespace PulsePC.Help;

/// <summary>Кусок текста справки. Рисуется в MainWindow.Help.cs стилями программы.</summary>
public abstract record HelpBlock;
/// <summary>Абзац.</summary>
public sealed record P(string Text) : HelpBlock;
/// <summary>Подзаголовок внутри раздела.</summary>
public sealed record H(string Text) : HelpBlock;
/// <summary>Нумерованные шаги.</summary>
public sealed record Steps(params string[] Items) : HelpBlock;
/// <summary>Список через тире.</summary>
public sealed record Dash(params string[] Items) : HelpBlock;
/// <summary>Таблица «название — пояснение».</summary>
public sealed record Rows(params (string Name, string Text)[] Items) : HelpBlock;
/// <summary>Выделенное примечание.</summary>
public sealed record Note(string Text) : HelpBlock;
/// <summary>Ссылка в программу: «tab:Сессии», «sys:Вентиляторы», «scan» — осмотр системы.</summary>
public sealed record Go(string Text, string Target) : HelpBlock;

/// <summary>Раздел справки: группа в списке слева, заголовок, вступление и содержание.</summary>
public sealed class HelpSection
{
    public string Group { get; init; }
    public string Title { get; init; }
    public string Lead { get; init; } = "";
    public HelpBlock[] Blocks { get; init; } = System.Array.Empty<HelpBlock>();
}

